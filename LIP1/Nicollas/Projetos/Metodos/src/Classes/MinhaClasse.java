package Classes;

public class MinhaClasse {

    private int numComida;

    private int quantComida;

    private int valComida;

    public void setNumComida(int numComida) {
        this.numComida = numComida;
    }
    public void setQuantComida(int quantComida) {
        this.quantComida = quantComida;
    }
    public void setValComida(int valComida) {
        this.valComida = valComida;
    }

    public int getNumComida() {
        return this.numComida;
    }
    public int getQuantComida() {
        return this.quantComida;
    }
    public int getValComida() {
        return this.valComida;
    }

}
